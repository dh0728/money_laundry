import { fireEvent, render, screen, waitFor, cleanup } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { App } from './App'

beforeEach(() => { window.sessionStorage.clear(); window.localStorage.clear(); window.history.replaceState(null, '', '/#/login') })
afterEach(cleanup)
async function login() {
  fireEvent.click(screen.getByRole('button', { name: '샘플 계정으로 입장' }))
  await screen.findByRole('heading', { name: '내 담당 업무' })
}
describe('first bundle app journeys', () => {
  it('validates login, signs in, switches scopes and signs out', async () => {
    render(<App />)
    fireEvent.submit(screen.getByRole('form', { name: '로그인' }))
    expect(screen.getByRole('alert')).toHaveTextContent('아이디와 비밀번호')
    await login()
    expect(window.location.hash).toBe('#/dashboard/mine')
    fireEvent.click(screen.getByRole('link', { name: '전체' }))
    await screen.findByRole('heading', { name: '기관 탐지 현황' })
    fireEvent.click(screen.getByRole('button', { name: '로그아웃' }))
    await screen.findByRole('heading', { name: '로그인' })
    expect(window.sessionStorage.getItem('aml-next-session')).toBeNull()
  })
  it('has distinct loading, empty and error states, and refetch preserves existing cases', async () => {
    window.history.replaceState(null, '', '/?state=loading#/login')
    render(<App />)
    await login()
    expect(screen.getByRole('status')).toHaveTextContent('불러오는 중')
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'ready' } })
    expect(screen.getAllByTestId('case-card').length).toBeGreaterThan(0)
    const count = screen.getAllByTestId('case-card').length
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'error' } })
    expect(screen.getByRole('alert')).toHaveTextContent('마지막으로 불러온 데이터')
    expect(screen.getAllByTestId('case-card')).toHaveLength(count)
    fireEvent.click(screen.getByRole('button', { name: '다시 시도' }))
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'empty' } })
    expect(screen.getByText('조건에 맞는 업무가 없습니다')).toBeInTheDocument()
    expect(screen.queryByTestId('case-card')).toBeNull()
  })
  it('removes sidebar when closed and keeps appearance on login expiry', async () => {
    render(<App />)
    await login()
    fireEvent.click(screen.getByRole('button', { name: '사이드바 접기' }))
    expect(screen.queryByRole('complementary', { name: '사이드바' })).toBeNull()
    fireEvent.change(screen.getByLabelText('테마'), { target: { value: 'solarized-dark' } })
    fireEvent.change(screen.getByLabelText('브랜드'), { target: { value: 'lime' } })
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'expired' } })
    await screen.findByText('세션이 만료되었습니다. 다시 로그인해 주세요.')
    expect(screen.getByLabelText('테마')).toHaveValue('solarized-dark')
    expect(screen.getByLabelText('브랜드')).toHaveValue('lime')
  })
  it('applies a period only after Apply and preserves it across scope navigation', async () => {
    render(<App />)
    await login()
    fireEvent.click(screen.getByText('11-09 ~ 11-15'))
    fireEvent.click(screen.getByRole('button', { name: '오늘' }))
    expect(window.location.hash).toBe('#/dashboard/mine')
    fireEvent.submit(screen.getByRole('form', { name: '조회 기간' }))
    expect(window.location.hash).toContain('start=2026-11-15')
    fireEvent.click(screen.getByRole('link', { name: '전체' }))
    await screen.findByRole('heading', { name: '기관 탐지 현황' })
    expect(window.location.hash).toContain('start=2026-11-15')
    expect(screen.getAllByTestId('case-card').length).toBe(3)
  })
  it('recovers corrupt appearance and invalid date URLs without crashing', async () => {
    window.localStorage.setItem('aml-next-appearance', 'null')
    window.sessionStorage.setItem('aml-next-session', 'sample-staff-7')
    window.history.replaceState(null, '', '/#/dashboard/mine?start=2026-02-31&end=garbage')
    render(<App />)
    expect(screen.getByLabelText('테마')).toHaveValue('light')
    expect(screen.getByText('11-09 ~ 11-15')).toBeInTheDocument()
  })
  it('clears only search when its filter chip is dismissed', async () => {
    window.sessionStorage.setItem('aml-next-session', 'sample-staff-7')
    window.history.replaceState(null, '', '/#/dashboard/all?start=2026-11-15&end=2026-11-15&q=missing')
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: '검색: missing 필터 해제' }))
    expect(window.location.hash).toContain('start=2026-11-15')
    expect(window.location.hash).not.toContain('q=')
  })
  it('keeps a successful empty snapshot when the next refetch fails', async () => {
    render(<App />)
    await login()
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'empty' } })
    expect(screen.queryByTestId('case-card')).toBeNull()
    fireEvent.change(screen.getByLabelText('검수 상태'), { target: { value: 'error' } })
    expect(screen.getByRole('alert')).toHaveTextContent('마지막으로 불러온 데이터')
    expect(screen.queryByTestId('case-card')).toBeNull()
  })
})
