import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { App } from './App'

beforeEach(() => { window.localStorage.clear(); window.sessionStorage.clear(); window.history.replaceState(null, '', '/#/login') })
afterEach(cleanup)
async function login() { render(<App />); fireEvent.click(screen.getByRole('button', { name: '샘플 계정으로 입장' })); await screen.findByRole('heading', { name: '내 담당 업무' }) }
async function go(path: string) { await act(async () => { window.history.pushState(null, '', `/#${path}`); window.dispatchEvent(new PopStateEvent('popstate')) }) }
describe('complete workspace integration', () => {
  it.each(['취소', '닫기', 'Escape'])('returns from account settings with %s without applying draft preferences', async close => {
    await login()
    const profile = screen.getByRole('button', { name: /님\s*조사 담당자 · 샘플 계정/ })
    profile.focus()
    fireEvent.click(profile)
    const account = await screen.findByRole('dialog', { name: '내 계정' })
    expect(account).toHaveAttribute('data-part', 'account-popover')
    expect(account.closest('[data-ui="aml-app"]')).not.toBeNull()
    expect(account).not.toHaveAttribute('aria-modal', 'true')
    expect(document.querySelector('[data-ws="dialog-overlay"]')).toBeNull()
    expect(within(account).queryByRole('button', { name: '설정' })).toBeNull()
    const gear = screen.getByRole('button', { name: '설정' })
    fireEvent.pointerDown(gear, { button: 0, pointerType: 'mouse' })
    gear.focus()
    fireEvent.click(gear)
    const settings = await screen.findByRole('dialog', { name: '설정' })
    expect(screen.queryByRole('dialog', { name: '내 계정' })).toBeNull()
    fireEvent.change(within(settings).getByLabelText('글자 크기'), { target: { value: 'large' } })
    if (close === 'Escape') fireEvent.keyDown(document.activeElement!, { key: 'Escape' })
    else fireEvent.click(within(settings).getByRole('button', { name: close }))
    const restored = await screen.findByRole('dialog', { name: '내 계정' })
    expect(document.querySelector('[data-ui="aml-app"]')).toHaveAttribute('data-font-size', 'default')
    await waitFor(() => expect(restored.contains(document.activeElement)).toBe(true))
    fireEvent.keyDown(document.activeElement!, { key: 'Escape' })
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    await waitFor(() => expect(profile).toHaveFocus())
  })

  it('keeps directly opened settings independent from the account popover', async () => {
    await login()
    const gear = screen.getByRole('button', { name: '설정' })
    gear.focus()
    fireEvent.click(gear)
    const settings = await screen.findByRole('dialog', { name: '설정' })
    fireEvent.click(within(settings).getByRole('button', { name: '취소' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    await waitFor(() => expect(gear).toHaveFocus())
  })

  it('discards session-only rule drafts after logout and a fresh login', async () => {
    await login()
    await go('/rules/new')
    fireEvent.change(await screen.findByLabelText('룰 이름'), { target: { value: '이전 세션 전용 초안' } })
    fireEvent.change(screen.getByLabelText('목적과 근거'), { target: { value: '로그아웃 이후 다른 세션에 남아서는 안 되는 샘플 작업' } })
    fireEvent.click(screen.getByRole('button', { name: '초안 저장' }))
    expect(await screen.findByRole('status')).toHaveTextContent('초안이 저장되었습니다')
    await go('/rules')
    expect(await screen.findByText('이전 세션 전용 초안')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: /님\s*조사 담당자 · 샘플 계정/ })); fireEvent.click(screen.getByRole('button', { name: '로그아웃' }))
    await screen.findByRole('heading', { name: '로그인' })
    fireEvent.click(screen.getByRole('button', { name: '샘플 계정으로 입장' }))
    await screen.findByRole('heading', { name: '내 담당 업무' })
    await go('/rules')
    await screen.findByRole('link', { name: '룰 만들기' })
    expect(screen.queryByText('이전 세션 전용 초안')).toBeNull()
  })
  it('connects detail judgment to shared report records and enforces read-only access', async () => {
    await login()
    await go('/alerts/8101?tab=overview')
    expect(await screen.findByRole('button', { name: '판정하기' })).toBeDisabled()
    await go('/alerts/8100?tab=overview')
    await waitFor(() => expect(screen.getByRole('button', { name: '판정하기' })).toBeEnabled())
    fireEvent.click(screen.getByRole('button', { name: '판정하기' }))
    const dialog = await screen.findByRole('dialog')
    fireEvent.click(within(dialog).getByLabelText('이상'))
    fireEvent.change(within(dialog).getByLabelText('판정 사유'), { target: { value: '공통 거래 근거 확인' } })
    fireEvent.click(within(dialog).getByRole('button', { name: '판정 완료' }))
    fireEvent.click(within(dialog).getByRole('button', { name: '확인 후 저장' }))
    expect(await within(dialog).findByRole('status')).toHaveTextContent('판정이 저장되었습니다')
    const report = within(dialog).getByRole('link', { name: '보고서 다운로드' })
    expect(report).toHaveAttribute('href', '#/report?selected=J-261115-000007')
    await go('/report?selected=J-261115-000007')
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect((await screen.findAllByText('공통 거래 근거 확인')).length).toBeGreaterThan(0)
    await go('/alerts/8100?tab=overview')
    expect(await screen.findByRole('button', { name: '판정하기' })).toBeDisabled()
  })
  it('shares rule creation across navigation and settings apply only on confirmation', async () => {
    await login()
    await go('/rules/new')
    fireEvent.change(await screen.findByLabelText('룰 이름'), { target: { value: '통합 검수 룰' } })
    fireEvent.change(screen.getByLabelText('목적과 근거'), { target: { value: '거래 점수와 기간을 검토하는 샘플 룰' } })
    fireEvent.click(screen.getByRole('button', { name: '초안 저장' }))
    expect(await screen.findByRole('status')).toHaveTextContent('초안이 저장되었습니다')
    await go('/dashboard/mine')
    await go('/rules')
    expect(await screen.findByText('통합 검수 룰')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '설정' }))
    const dialog = await screen.findByRole('dialog')
    fireEvent.change(within(dialog).getByLabelText('글자 크기'), { target: { value: 'large' } })
    expect(document.querySelector('[data-ui="aml-app"]')).toHaveAttribute('data-font-size', 'default')
    fireEvent.click(within(dialog).getByRole('button', { name: '설정 적용' }))
    expect(document.querySelector('[data-ui="aml-app"]')).toHaveAttribute('data-font-size', 'large')
  })
})
