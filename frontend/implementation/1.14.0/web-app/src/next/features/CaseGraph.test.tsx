import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import type { LedgerTransaction } from '../workspace-store'
import { CaseGraph, CaseTransactionTable } from './CaseGraph'

afterEach(cleanup)
function transactions(count: number): LedgerTransaction[] {
  return Array.from({ length: count }, (_, i) => ({ id: 7000 + i, displayId: `T-${7000 + i}`, date: '2026-11-15', occurredAt: `2026-11-15T12:${String(Math.floor(i / 60)).padStart(2, '0')}:${String(i % 60).padStart(2, '0')}Z`, typeCode: 3, probability: .8, suspicious: true, score: .95, amountUsd: 100, currency: 'USD', accountId: 900 + i, ownerId: 600 + i, fromAccountId: 900 + i, toAccountId: 901 + i, humanVerdict: null }))
}
describe('bounded case evidence rendering', () => {
  it('steps through evidence in timestamp order even when the server page is unordered', () => {
    const sorted = transactions(3), rows = [sorted[2], sorted[0], sorted[1]]
    render(<CaseGraph rows={rows} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '거래 재생 처음으로' }))
    fireEvent.click(screen.getByRole('button', { name: '다음 거래' }))
    expect(screen.getByRole('heading', { name: '분석 거래 1건' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: sorted[0].displayId })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: sorted[2].displayId })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '이전 거래' }))
    expect(screen.getByRole('heading', { name: '분석 거래 0건' })).toBeInTheDocument()
  })
  it('selects one directed connection and shows only its actual evidence', () => {
    const rows = transactions(3)
    render(<CaseGraph rows={rows} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:900>account:901' } })
    expect(screen.getByRole('heading', { name: '선택 연결 거래 1건' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: rows[0].displayId })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '연결 선택 해제' }))
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('links keyboard node selection to its evidence and clears with Escape', () => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    const node = screen.getByRole('button', { name: '계좌 900 선택' })
    fireEvent.keyDown(node, { key: 'Enter' })
    expect(screen.getByRole('heading', { name: '계좌 900 연결 거래 1건' })).toBeInTheDocument()
    fireEvent.keyDown(node, { key: 'Escape' })
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('renders 25 rows by default, paginates and never offers more than 100', () => {
    const rows = transactions(130), select = vi.fn()
    render(<CaseTransactionTable rows={rows} name="sample" onSelect={select} />)
    expect(screen.getByRole('heading', { name: '근거 거래 130건' })).toBeInTheDocument()
    expect(screen.getAllByRole('row')).toHaveLength(26)
    expect(screen.getByText('총 130건 · 1–25건 표시')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '다음' }))
    expect(screen.getByText('총 130건 · 26–50건 표시')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'T-7025' }))
    expect(select).toHaveBeenCalledWith(rows[25])
    fireEvent.change(screen.getByLabelText('페이지당 항목 수'), { target: { value: 100 } })
    expect(screen.getAllByRole('row')).toHaveLength(101)
    expect(screen.getAllByRole('option').map(option => option.getAttribute('value'))).toEqual(['25', '50', '100'])
  })
  it('selects an actual account neighborhood and updates its evidence table', () => {
    const rows = transactions(3)
    render(<CaseGraph rows={rows} ownershipLedger={new Map(rows.map(tx => [tx.accountId, tx.ownerId]))} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    expect(screen.getByRole('heading', { name: '계좌 901 연결 거래 2건' })).toBeInTheDocument()
    expect(screen.getAllByRole('row')).toHaveLength(3)
    fireEvent.click(screen.getByRole('button', { name: '계좌 선택 해제' }))
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('caps relationship nodes and distinguishes omitted evidence from the table total', () => {
    const rows = transactions(250)
    const { container } = render(<CaseGraph rows={rows} ownershipLedger={new Map(rows.map(tx => [tx.accountId, tx.ownerId]))} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    expect(container.querySelectorAll('[data-case="graph-node"]')).toHaveLength(200)
    expect(container.querySelectorAll('[data-case="edge"]').length).toBeLessThanOrEqual(400)
    expect(screen.getAllByRole('status').some(status => status.textContent?.includes('생략: 노드 51개, 연결 51개, 거래 51건'))).toBe(true)
    expect(screen.getByRole('heading', { name: '분석 거래 250건' })).toBeInTheDocument()
    expect(screen.getAllByRole('row')).toHaveLength(26)
  })
  it('applies analysis dates only after submit and retains the graph for an invalid period', () => {
    const rows = transactions(3)
    render(<CaseGraph rows={rows} ownershipLedger={new Map(rows.map(tx => [tx.accountId, tx.ownerId]))} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.change(screen.getByLabelText('거래 시작일'), { target: { value: '2026-11-16' } })
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
    fireEvent.submit(screen.getByRole('form', { name: '분석 기간' }))
    expect(screen.getByRole('heading', { name: '분석 거래 0건' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('거래 종료일'), { target: { value: '2026-11-14' } })
    fireEvent.submit(screen.getByRole('form', { name: '분석 기간' }))
    expect(screen.getByRole('alert')).toHaveTextContent('종료일은 시작일 이후')
    expect(screen.getByRole('heading', { name: '분석 거래 0건' })).toBeInTheDocument()
  })
  it.each(['pattern', 'owner'] as const)('highlights the selected transaction endpoints in %s view without filtering rows', lens => {
    const rows = transactions(3)
    const { container } = render(<CaseGraph rows={rows} ownershipLedger={new Map(rows.map(tx => [tx.accountId, tx.ownerId]))} lens={lens} name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'T-7000' }))
    const highlightedNodes = [...container.querySelectorAll('[data-case="graph-node"][data-highlighted]')].map(node => node.querySelector('strong')?.textContent)
    expect(highlightedNodes).toEqual(lens === 'pattern' ? ['계좌 900', '계좌 901'] : ['소유주 600', '소유주 601'])
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
    expect(container.querySelectorAll('tbody tr[data-selected]')).toHaveLength(1)
  })
  it('closes a standalone transaction detail and clears row and graph emphasis', () => {
    const { container } = render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'T-7000' }))
    expect(screen.getByRole('heading', { name: 'T-7000' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '거래 상세 닫기' }))
    expect(screen.queryByRole('heading', { name: 'T-7000' })).not.toBeInTheDocument()
    expect(container.querySelectorAll('[data-highlighted], tbody tr[data-selected]')).toHaveLength(0)
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('reserves a separate investigation detail region before selection and preserves it after close', () => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    const detail = screen.getByRole('complementary', { name: '조사 상세' })
    expect(within(detail).getByText('계좌 또는 거래를 선택하세요.')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'T-7000' }))
    expect(within(detail).getByRole('heading', { name: 'T-7000' })).toBeInTheDocument()
    expect(within(detail).queryByRole('form', { name: '분석 기간' })).not.toBeInTheDocument()
    fireEvent.click(within(detail).getByRole('button', { name: '거래 상세 닫기' }))
    expect(screen.getByRole('complementary', { name: '조사 상세' })).toBe(detail)
    expect(within(detail).getByText('계좌 또는 거래를 선택하세요.')).toBeInTheDocument()
  })
  it.each(['node', 'edge'])('keeps %s context and its automatic transaction detail in the reserved region', selection => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    if (selection === 'node') fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    else fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:901>account:902' } })
    const detail = within(screen.getByRole('complementary', { name: '조사 상세' }))
    expect(detail.getByRole('heading', { name: selection === 'node' ? '계좌 901' : '선택 연결' })).toBeInTheDocument()
    expect(detail.getByRole('heading', { name: 'T-7001' })).toBeInTheDocument()
    expect(detail.queryByText('표시 조건')).not.toBeInTheDocument()
  })
  it('returns keyboard focus to the transaction trigger after closing its inline detail', async () => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    const trigger = screen.getByRole('button', { name: 'T-7000' })
    trigger.focus()
    fireEvent.click(trigger)
    const close = screen.getByRole('button', { name: '거래 상세 닫기' })
    close.focus()
    fireEvent.click(close)
    await waitFor(() => expect(trigger).toHaveFocus())
  })
  it('returns to the first visible transaction when clearing a neighborhood removes the original trigger', async () => {
    render(<CaseGraph rows={transactions(130)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '다음' }))
    fireEvent.click(screen.getByRole('button', { name: '계좌 900 선택' }))
    const trigger = screen.getByRole('button', { name: 'T-7000' })
    trigger.focus()
    fireEvent.click(trigger)
    const close = screen.getByRole('button', { name: '거래 상세 닫기' })
    close.focus()
    fireEvent.click(close)
    expect(trigger.isConnected).toBe(false)
    await waitFor(() => expect(screen.getByRole('button', { name: 'T-7025' })).toHaveFocus())
    expect(screen.getByText('총 130건 · 26–50건 표시')).toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'T-7025' })).not.toBeInTheDocument()
  })
  it.each(['node', 'edge'])('keeps keyboard focus after closing automatic %s transaction details', async selection => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    if (selection === 'node') fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    else fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:901>account:902' } })
    const close = screen.getByRole('button', { name: '거래 상세 닫기' })
    close.focus()
    fireEvent.click(close)
    await waitFor(() => expect(screen.getByRole('button', { name: 'T-7000' })).toHaveFocus())
    expect(screen.queryByRole('button', { name: '거래 상세 닫기' })).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it.each(['node', 'edge'])('returns keyboard focus when the %s selection-reset button disappears', async selection => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    if (selection === 'node') fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    else fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:901>account:902' } })
    const reset = screen.getByRole('button', { name: selection === 'node' ? '계좌 선택 해제' : '연결 선택 해제' })
    reset.focus()
    fireEvent.click(reset)
    await waitFor(() => expect(screen.getByRole('button', { name: 'T-7000' })).toHaveFocus())
    expect(screen.queryByRole('button', { name: '거래 상세 닫기' })).not.toBeInTheDocument()
  })
  it.each(['node-close', 'node-reset', 'edge-close', 'edge-reset'])('keeps %s keyboard focus inside the fullscreen graph', async action => {
    const { container } = render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    const surface = container.querySelector('[data-case="analysis-layout"]')!
    const originalFullscreen = Object.getOwnPropertyDescriptor(document, 'fullscreenElement')
    Object.defineProperty(document, 'fullscreenElement', { configurable: true, get: () => surface })
    try {
      if (action.startsWith('node')) fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
      else fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:901>account:902' } })
      const name = action.endsWith('close') ? '거래 상세 닫기' : action.startsWith('node') ? '계좌 선택 해제' : '연결 선택 해제'
      const control = screen.getByRole('button', { name })
      control.focus()
      fireEvent.click(control)
      await waitFor(() => expect(screen.getByLabelText('연결 선택')).toHaveFocus())
      expect(surface.contains(document.activeElement)).toBe(true)
      expect(screen.queryByRole('button', { name: '거래 상세 닫기' })).not.toBeInTheDocument()
    } finally {
      if (originalFullscreen) Object.defineProperty(document, 'fullscreenElement', originalFullscreen)
      else Reflect.deleteProperty(document, 'fullscreenElement')
    }
  })
  it('does not transfer explicit transaction emphasis to a fallback row when replay is rewound', () => {
    const { container } = render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    fireEvent.click(screen.getByRole('button', { name: 'T-7001' }))
    expect(container.querySelectorAll('[data-case="graph-node"][data-highlighted]')).toHaveLength(2)
    fireEvent.change(screen.getByLabelText('거래 재생 위치'), { target: { value: 1 } })
    expect(screen.getByRole('heading', { name: '계좌 901 연결 거래 1건' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'T-7000' })).toBeInTheDocument()
    expect(container.querySelectorAll('[data-highlighted]')).toHaveLength(0)
    fireEvent.change(screen.getByLabelText('거래 재생 위치'), { target: { value: 3 } })
    expect([...container.querySelectorAll('[data-case="graph-node"][data-highlighted] strong')].map(node => node.textContent)).toEqual(['계좌 901', '계좌 902'])
  })
  it('retains a selected account neighborhood when opening one of its transactions', () => {
    const { container } = render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    fireEvent.click(screen.getByRole('button', { name: 'T-7000' }))
    expect(screen.getByRole('heading', { name: '계좌 901 연결 거래 2건' })).toBeInTheDocument()
    expect(container.querySelectorAll('[data-case="graph-node"][data-highlighted]')).toHaveLength(2)
    fireEvent.keyDown(screen.getByRole('button', { name: '계좌 902 선택' }), { key: 'Enter' })
    expect(screen.getByRole('heading', { name: '계좌 902 연결 거래 2건' })).toBeInTheDocument()
    expect(container.querySelectorAll('[data-highlighted]')).toHaveLength(0)
    fireEvent.keyDown(screen.getByRole('button', { name: '계좌 902 선택' }), { key: 'Escape' })
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('remaps transaction emphasis to actual owner groups when the lens changes', () => {
    const rows = transactions(3), owners = new Map([[900, 600], [901, 601], [902, 600]])
    const props = { rows, ownershipLedger: owners, name: 'sample', editable: true, onVerdict: vi.fn() }
    const { container, rerender } = render(<CaseGraph {...props} lens="pattern" />)
    fireEvent.click(screen.getByRole('button', { name: 'T-7000' }))
    rerender(<CaseGraph {...props} lens="owner" />)
    expect([...container.querySelectorAll('[data-case="graph-node"][data-highlighted] strong')].map(node => node.textContent)).toEqual(['소유주 600', '소유주 601'])
    expect(screen.getByRole('heading', { name: 'T-7000' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
  })
  it('requests a server neighborhood for oversized input without touching transaction rows', () => {
    const inaccessible = new Proxy(new Array<LedgerTransaction>(10_001), {
      get(target, property) {
        if (property === 'length') return target.length
        throw new Error(`Oversized input was accessed: ${String(property)}`)
      },
    })
    const { container } = render(<CaseGraph rows={inaccessible} ownershipLedger={new Map()} lens="pattern" name="sample" editable onVerdict={vi.fn()} />)
    expect(screen.getByRole('status')).toHaveTextContent('서버에서 기간·계좌 범위를 좁힌 이웃 조회가 필요합니다')
    expect(container.querySelectorAll('[data-case="graph-node"], [data-case="edge"]')).toHaveLength(0)
    expect(screen.queryByRole('table')).not.toBeInTheDocument()
  })
  it('keeps related scope controls beside the graph without a reserved empty detail or transaction table', () => {
    const { container } = render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="owner" name="related" editable={false} onVerdict={vi.fn()} layout="related" showTransactions={false} scopeControls={<fieldset><legend>관련 업무 범위</legend><label><input type="checkbox" defaultChecked />현재 업무</label></fieldset>} />)
    expect(screen.getByRole('group', { name: '관련 업무 범위' })).toBeInTheDocument()
    const side = container.querySelector('[data-case="analysis-side"]')!
    expect(side.firstElementChild).toContainElement(screen.getByRole('group', { name: '관련 업무 범위' }))
    expect(screen.queryByRole('complementary', { name: '조사 상세' })).not.toBeInTheDocument()
    expect(screen.queryByRole('table')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '거래 재생' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '확대' })).toBeInTheDocument()
  })
  it.each(['node', 'edge'])('opens an actual %s transaction in related view and restores focus without a transaction table', async selection => {
    const rows = transactions(3)
    const { container } = render(<CaseGraph rows={rows} ownershipLedger={new Map()} lens="pattern" name="related" editable={false} onVerdict={vi.fn()} layout="related" showTransactions={false} />)
    if (selection === 'node') fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    else fireEvent.change(screen.getByLabelText('연결 선택'), { target: { value: 'account:901>account:902' } })
    const detail = screen.getByRole('complementary', { name: '조사 상세' })
    expect(detail.parentElement).toBe(container.querySelector('[data-case="analysis-layout"]'))
    expect(within(detail).getByRole('heading', { name: 'T-7001' })).toBeInTheDocument()
    expect(within(detail).getByRole('button', { name: '정상으로 판정' })).toBeDisabled()
    const close = within(detail).getByRole('button', { name: '거래 상세 닫기' })
    close.focus()
    fireEvent.click(close)
    await waitFor(() => expect(screen.getByLabelText('연결 선택')).toHaveFocus())
    expect(screen.queryByRole('complementary', { name: '조사 상세' })).not.toBeInTheDocument()
    expect(screen.queryByRole('table')).not.toBeInTheDocument()
  })
  it('restores focus when only the evidence table is hidden in analysis view', async () => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="sample" editable={false} onVerdict={vi.fn()} showTransactions={false} />)
    fireEvent.click(screen.getByRole('button', { name: '계좌 901 선택' }))
    const close = screen.getByRole('button', { name: '거래 상세 닫기' })
    close.focus()
    fireEvent.click(close)
    await waitFor(() => expect(screen.getByLabelText('연결 선택')).toHaveFocus())
    expect(screen.getByRole('complementary', { name: '조사 상세' })).toBeInTheDocument()
    expect(screen.queryByRole('table')).not.toBeInTheDocument()
  })
  it('keeps the evidence table by default in related view', () => {
    render(<CaseGraph rows={transactions(3)} ownershipLedger={new Map()} lens="pattern" name="related" editable={false} onVerdict={vi.fn()} layout="related" />)
    expect(screen.getByRole('heading', { name: '분석 거래 3건' })).toBeInTheDocument()
    expect(screen.getByRole('table')).toBeInTheDocument()
  })

})
