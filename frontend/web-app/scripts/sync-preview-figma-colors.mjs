import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { colorToCss } from './sync-semantic-tokens.mjs'

const fileKey = 'eHgUPAyr9bZ2UC7oTZNmwh'
const collectionName = 'Color Semantic'
const modes = ['Light', 'Dark']
const tokenPrefix = '--aml-figma-'
const directory = resolve(import.meta.dirname, '../live-layout')
const snapshotPath = resolve(directory, 'figma-colors.json')
const cssPath = resolve(directory, 'figma-colors.css')
const sourceMode = name => name.toLowerCase()
const slug = name => name.replaceAll('/', '-')

function normalizeColor(value, name) {
  const match = typeof value === 'string' && value.match(/^(#[0-9a-f]{6})(?:\/(0(?:\.\d+)?|\.\d+|1(?:\.0+)?))?$/i)
  if (!match) throw new Error(`Invalid color for "${name}". Expected #rrggbb or #rrggbb/alpha with alpha between 0 and 1.`)
  const [, hex, opacity] = match
  if (opacity === undefined || Number(opacity) === 1) return hex.toLowerCase()
  const alpha = opacity.startsWith('.') ? `0${opacity}` : opacity
  return `${hex.toLowerCase()}/${alpha.includes('.') ? alpha.replace(/0+$/, '').replace(/\.$/, '') : alpha}`
}

export function normalizePreviewColors(snapshot) {
  if (snapshot?.collection !== collectionName
    || !Array.isArray(snapshot.modes) || snapshot.modes.length !== modes.length
    || !modes.every(mode => snapshot.modes.includes(mode))) {
    throw new Error('Expected the "Color Semantic" collection with "Light" and "Dark" modes.')
  }
  if (!Array.isArray(snapshot.colors) || !snapshot.colors.length) throw new Error('Color Semantic has no colors.')

  const properties = new Set()
  const colors = snapshot.colors.map(row => {
    if (!Array.isArray(row) || row.length !== modes.length + 1) throw new Error('Expected a [name, light, dark] color tuple.')
    const [name] = row
    if (typeof name !== 'string' || !/^(?:[a-z\d][a-z\d-]*\/)*[a-z\d][a-z\d-]*$/i.test(name)) {
      throw new Error(`Invalid color name: ${JSON.stringify(name)}`)
    }
    const propertyName = slug(name)
    for (const property of [propertyName, ...modes.map(mode => `${sourceMode(mode)}-${propertyName}`)]) {
      if (properties.has(property)) throw new Error(`Duplicate CSS property: ${tokenPrefix}${property}`)
      properties.add(property)
    }
    return [name, ...modes.map(mode => normalizeColor(row[snapshot.modes.indexOf(mode) + 1], name))]
  }).sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0)

  return { collection: collectionName, modes: [...modes], colors }
}

export function generatePreviewColorCss(snapshot) {
  const declarations = normalizePreviewColors(snapshot).colors.flatMap(([name, light, dark]) => {
    const token = slug(name)
    const lightProperty = `${tokenPrefix}light-${token}`
    const darkProperty = `${tokenPrefix}dark-${token}`
    return [
      `  ${lightProperty}: ${colorToCss(light)};`,
      `  ${darkProperty}: ${colorToCss(dark)};`,
      `  ${tokenPrefix}${token}: light-dark(var(${lightProperty}), var(${darkProperty}));`,
    ]
  })
  return [
    '/* Generated by node scripts/sync-preview-figma-colors.mjs. Do not edit.',
    ` * Source: figma-colors.json (Figma ${fileKey}, Color Semantic).`,
    ' */',
    ':root {',
    ...declarations,
    '}',
    '',
  ].join('\n')
}

const isChannel = value => Number.isFinite(value) && value >= 0 && value <= 1

function serializeFigmaColor(color, name) {
  const rgb = [color?.r, color?.g, color?.b]
  const alpha = color?.a ?? 1
  if (!rgb.every(isChannel) || !isChannel(alpha)) throw new Error(`Invalid Figma color: ${name}`)
  const hex = `#${rgb.map(channel => Math.round(channel * 255).toString(16).padStart(2, '0')).join('')}`
  return alpha === 1 ? hex : `${hex}/${alpha.toFixed(12)}`
}

export function snapshotFromFigmaVariables(response) {
  const { variables, variableCollections } = response?.meta ?? {}
  if (response?.error || !variables || !variableCollections) throw new Error('Figma did not return local variables.')
  const collections = new Map(Object.entries(variableCollections))
  const semantic = [...collections.values()].filter(collection => collection.name === collectionName && !collection.remote)
  if (semantic.length !== 1 || semantic[0].isExtension) throw new Error('Expected one local, non-extended "Color Semantic" collection.')
  const [collection] = semantic
  for (const mode of modes) {
    if (!collection.modes.some(item => item.name === mode)) throw new Error(`Color Semantic mode is missing: ${mode}`)
  }
  const byId = new Map(Object.entries(variables))
  for (const variable of byId.values()) {
    if (!byId.has(variable.id)) byId.set(variable.id, variable)
  }

  function resolveRaw(value, modeName, trail) {
    if (value?.type === 'VARIABLE_ALIAS') return resolveValue(value.id, modeName, trail)
    if (value && Object.hasOwn(value, 'color') && Object.hasOwn(value, 'opacity')) {
      const color = resolveRaw(value.color, modeName, trail)
      const opacity = resolveRaw(value.opacity, modeName, trail)
      if (!Number.isFinite(opacity) || opacity < 0 || opacity > 100) throw new Error('Invalid Figma composed-color opacity.')
      return { ...color, a: opacity / 100 }
    }
    return value
  }

  function resolveValue(id, modeName, trail = []) {
    const variable = byId.get(id)
    if (!variable) throw new Error(`Missing Figma alias target: ${id}`)
    if (trail.includes(variable.id)) throw new Error(`Alias cycle: ${[...trail, variable.id].join(' -> ')}`)
    const owner = collections.get(variable.variableCollectionId)
    const modeId = owner?.modes.find(mode => mode.name === modeName)?.modeId ?? owner?.defaultModeId
    const value = variable.valuesByMode?.[modeId]
    if (value === undefined) throw new Error(`Missing Figma value: ${variable.name} (${modeName})`)
    return resolveRaw(value, modeName, [...trail, variable.id])
  }

  const colors = collection.variableIds.flatMap(id => {
    const variable = byId.get(id)
    if (!variable) throw new Error(`Missing Figma variable: ${id}`)
    if (variable.resolvedType !== 'COLOR' || variable.deletedButReferenced) return []
    return [[variable.name, ...modes.map(mode => serializeFigmaColor(resolveValue(id, mode), variable.name))]]
  })
  return normalizePreviewColors({ collection: collectionName, modes, colors })
}

async function fetchSnapshot() {
  const token = process.env.FIGMA_TOKEN
  if (!token) throw new Error('Set FIGMA_TOKEN for --fetch, or import a resolved Figma snapshot with --input.')
  const response = await fetch(`https://api.figma.com/v1/files/${fileKey}/variables/local`, {
    headers: { 'X-Figma-Token': token },
    redirect: 'error',
    signal: AbortSignal.timeout(15000),
  })
  if (!response.ok) throw new Error(`Figma local variables returned HTTP ${response.status}. The endpoint requires Enterprise access and file_variables:read. You can use --input with the Figma export.`)
  return snapshotFromFigmaVariables(await response.json())
}

const readSnapshot = async path => normalizePreviewColors(JSON.parse(await readFile(path, 'utf8')))

async function run() {
  const { values } = parseArgs({
    options: {
      check: { type: 'boolean' }, fetch: { type: 'boolean' }, input: { type: 'string' }, help: { type: 'boolean' },
    },
  })
  if (values.help) {
    console.log('Usage: node scripts/sync-preview-figma-colors.mjs [--check] [--input <path> | --fetch]\nDefaults to the cached live-layout/figma-colors.json. --fetch reads FIGMA_TOKEN from the environment.')
    return
  }
  if (values.fetch && values.input !== undefined) throw new Error('Choose one source: --input or --fetch.')
  const importing = values.fetch || values.input !== undefined
  const snapshot = values.fetch ? await fetchSnapshot() : await readSnapshot(values.input ?? snapshotPath)
  const css = generatePreviewColorCss(snapshot)
  if (values.check) {
    const currentCss = await readFile(cssPath, 'utf8').catch(error => {
      if (error.code !== 'ENOENT') throw error
      return ''
    })
    const currentSnapshot = importing ? await readSnapshot(snapshotPath) : snapshot
    if (currentCss !== css || JSON.stringify(currentSnapshot) !== JSON.stringify(snapshot)) {
      throw new Error('Figma preview colors are stale. Rerun without --check to synchronize.')
    }
    console.log(`Verified ${snapshot.colors.length} Figma colors in the preview CSS.`)
    return
  }
  if (importing) await writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)
  await writeFile(cssPath, css)
  console.log(`Generated preview CSS with ${snapshot.colors.length} Figma colors.`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await run()
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
