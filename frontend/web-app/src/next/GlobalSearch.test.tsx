import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { GlobalSearch } from './GlobalSearch'
import { WorkspaceProvider } from './WorkspaceProvider'
import { App } from './App'

beforeEach(() => { window.localStorage.clear(); window.sessionStorage.clear(); window.history.replaceState(null, '', '/#/dashboard/mine') })
afterEach(cleanup)
function setup() { render(<div data-ui="aml-app"><WorkspaceProvider><GlobalSearch /></WorkspaceProvider></div>); fireEvent.click(screen.getByRole('button', { name: '전역 검색' })); return screen.getByRole('combobox', { name: '전역 검색어' }) }
describe('global workspace search', () => {
  it('focuses input, filters cases and opens the actual numeric case route with Enter', async () => {
    const input = setup()
    expect(input).toHaveFocus()
    fireEvent.change(input, { target: { value: 'A-261109-000041' } })
    expect(screen.getAllByRole('option')).toHaveLength(1)
    expect(screen.getByRole('option')).toHaveAttribute('href', '#/alerts/8100?tab=overview')
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(window.location.hash).toBe('#/alerts/8100?tab=overview')
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  })
  it('moves selected candidates with arrows and leaves horizontal text cursor keys alone', () => {
    const input = setup()
    const first = input.getAttribute('aria-activedescendant')
    fireEvent.mouseMove(screen.getAllByRole('option')[1])
    expect(input).toHaveAttribute('aria-activedescendant', first)
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    expect(input.getAttribute('aria-activedescendant')).not.toBe(first)
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    expect(input).toHaveAttribute('aria-activedescendant', first)
    fireEvent.keyDown(input, { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: '전체' })).toHaveAttribute('aria-selected', 'true')
    const all = screen.getByRole('tab', { name: '전체' })
    fireEvent.keyDown(all, { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: '대시보드' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getAllByRole('option')).toHaveLength(2)
  })
  it.each([{ isComposing: true }, { keyCode: 229 }])('ignores IME Enter and arrow navigation for %o', composition => {
    const input = setup()
    const active = input.getAttribute('aria-activedescendant')
    fireEvent.keyDown(input, { key: 'ArrowDown', ...composition })
    expect(input).toHaveAttribute('aria-activedescendant', active)
    fireEvent.keyDown(input, { key: 'Enter', ...composition })
    expect(screen.getByRole('dialog')).toBeInTheDocument()
    expect(window.location.hash).toBe('#/dashboard/mine')
    fireEvent.keyDown(screen.getByRole('tab', { name: '전체' }), { key: 'ArrowRight', ...composition })
    expect(screen.getByRole('tab', { name: '전체' })).toHaveAttribute('aria-selected', 'true')
  })
  it('preserves dashboard query filtering alongside global search', async () => {
    window.sessionStorage.setItem('aml-next-session', 'sample-staff-7')
    render(<App />)
    fireEvent.change(screen.getByLabelText('업무 검색어'), { target: { value: 'A-261109-000041' } })
    expect(screen.getAllByTestId('case-card').length).toBeGreaterThan(1)
    fireEvent.submit(screen.getByRole('search', { name: '업무 검색' }))
    await waitFor(() => expect(screen.getAllByTestId('case-card')).toHaveLength(1))
    expect(window.location.hash).toContain('q=A-261109-000041')
    expect(screen.getByRole('button', { name: '전역 검색' })).toBeInTheDocument()
  })
  it('returns only real rule/transaction results and renders the specified empty state', () => {
    const input = setup()
    fireEvent.click(screen.getByRole('tab', { name: '룰 엔진' }))
    fireEvent.change(input, { target: { value: 'RULE-001' } })
    expect(screen.getByRole('option')).toHaveAttribute('href', '#/rules?selected=RULE-001')
    fireEvent.click(screen.getByRole('tab', { name: '거래' }))
    fireEvent.change(input, { target: { value: 'T-261109-00000001' } })
    expect(screen.getByRole('option')).toHaveAttribute('href', '#/investigate/ledger?transaction=7000')
    fireEvent.change(input, { target: { value: '없는 항목 qqq' } })
    expect(screen.queryByRole('option')).toBeNull()
    expect(screen.getByRole('status')).toHaveTextContent('맞는 항목이 없습니다.검색어를 바꿔 보세요.')
  })
  it('restores trigger focus on Escape and only prioritizes actually opened cases', async () => {
    const input = setup()
    expect(screen.getByRole('option', { selected: true })).toHaveTextContent('내 담당 대시보드')
    fireEvent.change(input, { target: { value: 'A-261109-000041' } })
    fireEvent.click(screen.getByRole('option'))
    fireEvent.click(screen.getByRole('button', { name: '전역 검색' }))
    expect(screen.getByRole('option', { selected: true })).toHaveTextContent('A-261109-000041')
    fireEvent.keyDown(screen.getByRole('combobox'), { key: 'Escape' })
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(screen.getByRole('button', { name: '전역 검색' })).toHaveFocus()
  })
  it('navigates from the actual sidebar dialog to the case screen', async () => {
    window.sessionStorage.setItem('aml-next-session', 'sample-staff-7')
    render(<App />)
    fireEvent.click(screen.getByRole('button', { name: '전역 검색' }))
    fireEvent.change(screen.getByRole('combobox'), { target: { value: 'A-261109-000041' } })
    await act(async () => { fireEvent.keyDown(screen.getByRole('combobox'), { key: 'Enter' }); window.dispatchEvent(new HashChangeEvent('hashchange')) })
    expect(await screen.findByRole('button', { name: '판정하기' })).toBeInTheDocument()
    expect(screen.queryByRole('dialog')).toBeNull()
  })
})
